local regions = dofile('lib/midi_region_bounds.lua')
local function near(actual, expected)
    assert(math.abs(actual - expected) < 1e-10,
        string.format('%.12f ~= %.12f', actual, expected))
end
local project = {}
local identity = {
    TimeMap2_QNToTime = function(p, qn) assert(p == project); return qn end,
    TimeMap2_timeToQN = function(p, time) assert(p == project); return time end,
    TimeMap_QNToMeasures = function(_, qn)
        local first = math.floor(qn / 4) * 4
        return first / 4, first, first + 4
    end,
}
local function limit(list, start, finish, left, right, expected_left, expected_right, api)
    local a, b = regions.limit(api or identity, project, list, start, finish, left, right)
    near(a, expected_left); near(b, expected_right)
end

-- Marker counts include both markers and regions; only nonempty regions count.
local entries = {
    { false, 1, 0 }, { true, 4.5, 11.5 }, { false, 8, 0 },
    { true, 6, 6 }, { true, 10, 9 }, { true, 15, 17.25 },
}
local enumerated = {}
local api = {
    CountProjectMarkers = function(p) assert(p == project); return #entries, 2, 4 end,
    EnumProjectMarkers3 = function(p, i)
        assert(p == project)
        enumerated[#enumerated + 1] = i
        local entry = assert(entries[i + 1])
        return i + 1, entry[1], entry[2], entry[3], 'boundary', i
    end,
}
local found = regions.collect(api, project)
assert(#found == 2 and found[1].first == 4.5 and found[1].last == 11.5)
assert(found[2].first == 15 and found[2].last == 17.25)
assert(#enumerated == #entries and enumerated[1] == 0 and enumerated[#entries] == #entries - 1)
api.CountProjectMarkers = function() return 0, 0, 0 end
assert(#regions.collect(api, project) == 0)
api.CountProjectMarkers = function() return 1, 0, 1 end
api.EnumProjectMarkers3 = function() return 0 end
assert(not pcall(regions.collect, api, project), 'Failed enumeration must stop planning.')

-- Off-bar region starts/ends cap outward padding. Edges on those boundaries
-- stay exact, including candidates generated by the manual lead-in rule.
local one = { { first = 4.5, last = 11.5 } }
limit(one, 5, 11.5, 4, 12, 4.5, 11.5)
limit(one, 4.5, 11, 0, 12, 4.5, 11.5)
limit(one, 4.5, 11.5, 4, 12, 4.5, 11.5)
-- Region boundaries farther away than the enclosing bar do not lengthen it.
limit({ { first = 1, last = 15 } }, 5, 7, 4, 8, 4, 8)
-- No regions retains normal enclosing bars; project zero remains a hard floor.
limit({}, 5, 7, 4, 8, 4, 8)
limit({}, .2, 3.5, -4, 4, 0, 4)
limit({}, 0, 3.5, -4, 4, 0, 4)
-- An existing negative-time item is not moved later merely to clamp to zero.
limit({}, -1, 3.5, -4, 4, -4, 4)

-- Nested and overlapping region edges resolve independently: whichever
-- qualifying boundary is nearest wins, regardless of enumeration order.
local nested = {
    { first = 1, last = 15 }, { first = 4.5, last = 11.5 },
    { first = 4.75, last = 11.75 },
}
limit(nested, 5, 11, 4, 12, 4.75, 11.5)
limit({ nested[3], nested[1], nested[2] }, 5, 11, 4, 12, 4.75, 11.5)
limit({ nested[2], nested[3], nested[1] }, 5, 11, 4, 12, 4.75, 11.5)

-- At a shared boundary, a left edge belongs to the following region and a
-- right edge belongs to the preceding region; neither crosses the boundary.
local adjacent = { { first = 4.5, last = 8.5 }, { first = 8.5, last = 11.5 } }
limit(adjacent, 8.5, 10, 8, 12, 8.5, 11.5)
limit(adjacent, 5, 8.5, 4, 12, 4.5, 8.5)
limit({ adjacent[2], adjacent[1] }, 8.5, 10, 8, 12, 8.5, 11.5)
limit({ adjacent[2], adjacent[1] }, 5, 8.5, 4, 12, 4.5, 8.5)
-- A span across two regions can use their outer edge limits without snapping
-- to any interior boundary, truncating the item, or jumping across the gap.
limit({ { first = 4.5, last = 8.5 }, { first = 12.5, last = 15.5 } },
    5, 15, 4, 16, 4.5, 15.5)
limit({ { first = 6, last = 7 } }, 5, 11, 4, 12, 4, 12)

-- Nearby overhangs trim inward, including both sides of the same region.
limit(one, 4.5 - 5e-8, 11.5 + 5e-8, 4, 12, 4.5, 11.5)
limit(one, 4.5 - 1e-4, 11.5 + 1e-4, 4, 12, 4.5, 11.5)
limit(one, 5, 11.5 + 1e-4, 4, 12, 4.5, 11.5)
limit(one, 4.5 - 1e-4, 11, 4, 12, 4.5, 11.5)
limit(one, 4, 12, 0, 12, 4.5, 11.5) -- Repair old bar rounding.
limit({ { first = 4, last = 12 } }, 5, 12.072, 4, 16, 4, 12)
limit({ { first = 4, last = 12 } }, 5, 16, 4, 16, 4, 12)
-- A long item extending beyond the boundary bar is not collapsed into a region.
limit(one, 5, 16.5, 4, 20, 4.5, 20)
-- A genuine span into an adjacent region retains that part of the item.
limit(adjacent, 5, 10, 4, 12, 4.5, 11.5)
limit(adjacent, 7, 11, 4, 12, 4.5, 11.5)
-- Resolve padding-induced region association on the first run, not the next.
local association = { { first = 23.5, last = 40.75 } }
limit(association, 20, 27, 20, 28, 23.5, 28)
limit(association, 23.5, 28, 20, 28, 23.5, 28)

-- Limits are measured in seconds then converted through the project's tempo
-- map; region edges need not share a QN or seconds grid with the barlines.
local tempo = {
    TimeMap_QNToMeasures = identity.TimeMap_QNToMeasures,
    TimeMap2_QNToTime = function(p, qn)
        assert(p == project)
        return qn <= 4 and qn / 2 or 2 + qn - 4
    end,
    TimeMap2_timeToQN = function(p, time)
        assert(p == project)
        return time <= 2 and time * 2 or 4 + time - 2
    end,
}
limit({ { first = .75, last = 5.5 } }, 1, 5, 0, 8, 1.5, 7.5, tempo)

print('PASS: marker filtering, off-bar region limits, nested/overlapping/adjacent regions, spanning items, noise/overhang, project zero, tempo conversion')
